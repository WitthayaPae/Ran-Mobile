'use strict';
//
// Extract the byte-substitution tables from SOURCE and emit bytecrypt.json.
//
//   node gen-bytecrypt.js > bytecrypt.json
//
// Every encrypted game-data format in this engine (`.lev`, `.egp`, `.cfg`,
// `.wld`, `.qst`, `.ntk`, `.crowsale`, animation `.bin`, ...) is protected by
// the same mechanism: a per-format 256-byte substitution table.
//
//   encode: b -> ARRAY[b]
//   decode: build the inverse of ARRAY, then b -> INVERSE[b]
//
// (BYTECRYPT::byte_encode / byte_decode, Lib_Engine/Common/ByteCrypt.cpp)
//
// The tables are 43 arrays of 256 hex bytes. Transcribing them by hand is
// exactly the failure mode this project keeps hitting, so they are parsed out
// of the headers instead. The enum -> array mapping is read from the
// InitArray() body rather than guessed from names, because several do not
// match (e.g. EMBYTECRYPT_LEVEL uses ARRAY_LEVEL_VAR1).
//
const fs = require('fs');
const path = require('path');

const COMMON = path.join(__dirname, '..', '..', '..',
                         'SOURCE', 'Lib_Engine', 'Common');

const HEADERS = [
  'ByteCryptDef.h',
  'ByteCryptDefVer1.h',
  'ByteCryptDefVer2.h',
  'ByteCryptDefLevelNew.h',
];

// name -> number[256]
const arrays = new Map();
for (const h of HEADERS) {
  const file = path.join(COMMON, h);
  if (!fs.existsSync(file)) continue;
  const src = fs.readFileSync(file, 'utf8');
  const re = /UCHAR\s+(ARRAY_\w+)\s*\[\s*256\s*\]\s*=\s*\{([^}]*)\}/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const name = m[1];
    const bytes = m[2].match(/0x[0-9a-fA-F]{1,2}/g);
    if (!bytes || bytes.length !== 256) {
      throw new Error(`${name}: expected 256 bytes, parsed ${bytes ? bytes.length : 0}`);
    }
    arrays.set(name, bytes.map((b) => parseInt(b, 16)));
  }
}

// Enum name -> array name, taken from InitArray().
const initSrc = fs.readFileSync(path.join(COMMON, 'ByteCrypt.cpp'), 'utf8');
const mapping = new Map();
const mapRe = /ARRAY_USE\[\s*(EMBYTECRYPT_\w+)\s*\]\[i\]\s*=\s*(ARRAY_\w+)\[i\]/g;
let mm;
while ((mm = mapRe.exec(initSrc)) !== null) mapping.set(mm[1], mm[2]);

// Enum name -> numeric value, from ByteCrypt.h.
const enumSrc = fs.readFileSync(path.join(COMMON, 'ByteCrypt.h'), 'utf8');
const values = new Map();
const enumRe = /(EMBYTECRYPT_\w+)\s*=\s*(\d+)/g;
let em;
while ((em = enumRe.exec(enumSrc)) !== null) values.set(em[1], Number(em[2]));

const out = { note: 'generated by gen-bytecrypt.js from SOURCE; do not edit',
              tables: {} };
let missing = [];
for (const [enumName, arrayName] of mapping) {
  const table = arrays.get(arrayName);
  if (!table) { missing.push(`${enumName} -> ${arrayName}`); continue; }
  out.tables[enumName] = { id: values.get(enumName), array: arrayName, encode: table };
}

if (missing.length) out.missing = missing;
out.count = Object.keys(out.tables).length;
process.stdout.write(JSON.stringify(out, null, 1) + '\n');
